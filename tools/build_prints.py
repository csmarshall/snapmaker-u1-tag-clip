"""Build everything and publish the ready-to-slice 3MFs into prints/ (tracked, unlike chip/out and u1/out), plus prints/README.md listing them.

Writes prints/chips/tag-clip_<stem>.3mf (one per filament), prints/tag-clip_all-chips.3mf (every chip on one plate) and prints/u1/u1_docks_fingers_set.3mf (the four docks with socket fingers), and deletes anything else under prints/ so a removed filament does not leave a stale file.
The 3MFs are byte-reproducible for a given toolchain (uv.lock): the same geometry rebuilds to identical files on one machine; across operating systems that is not yet verified. Run from anywhere: uv run python tools/build_prints.py
Set TAG_CLIP_LOG_LEVEL (DEBUG, INFO, WARNING, ...) to change the log level; the default is INFO.
"""
import logging
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # the repository root
for sub in ("chip", "u1", "u1/tools"):
    sys.path.insert(0, str(ROOT / sub))
import chip_clip  # noqa: E402
import make_3mf  # noqa: E402
import print_plates as P  # noqa: E402
import u1_build  # noqa: E402

LOG_LEVEL_ENV = "TAG_CLIP_LOG_LEVEL"
LOG_FORMAT = "%(asctime)s %(levelname)s %(message)s"
PRINTS = ROOT / "prints"
CHIPS_DIR = PRINTS / "chips"
U1_DIR = PRINTS / "u1"
ALL_CHIPS_3MF = PRINTS / f"{chip_clip.CHIP_FILE_PREFIX}all-chips.3mf"
DOCKS_SET_3MF = U1_DIR / "u1_docks_fingers_set.3mf"
README = PRINTS / "README.md"
ALL_CHIPS_TITLE = "Tag clip chips, one of every filament (PETG)"
DOCKS_SET_TITLE = "U1 docks with socket fingers, slots 1 to 4 (PETG)"

log = logging.getLogger("build_prints")


def assert_fits_one_plate(table: tuple) -> None:
    """Lay the parts out and raise AssertionError if any part would land outside the bed, i.e. the layout spilled past one plate's depth (or width)."""
    placed = P.lay_out(table)
    assert list(placed) == [1], f"parts are on plates {sorted(placed)}, expected one plate"
    for axis, name in ((0, "X"), (1, "Y")):
        hi = max(m.bounds[1][axis] for p in placed[1] for _, _, m in p["files"])
        low = min(m.bounds[0][axis] for p in placed[1] for _, _, m in p["files"])
        assert hi - low <= P.BED, f"the {len(table)} parts need {hi - low:.1f} mm along {name}, more than the {P.BED:.0f} mm bed"


def build_outputs() -> None:
    """Run the full chip build (with the label STLs) and the U1 build into chip/out and u1/out."""
    log.info("building chips and generic docks")
    chip_clip.build_chips_and_docks([], label_stl=True)
    log.info("building U1 parts")
    u1_build.main()


def write_prints() -> list[Path]:
    """Write every published file (except the README) and return their paths."""
    CHIPS_DIR.mkdir(parents=True, exist_ok=True)
    U1_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for material in chip_clip.FILAMENTS:
        stem = chip_clip.chip_file_stem(material)
        dest = CHIPS_DIR / f"{stem}.3mf"
        shutil.copyfile(P.CHIP_OUT / f"{stem}.3mf", dest)
        written.append(dest)
    assert_fits_one_plate(P.ALL_CHIPS_PARTS)
    make_3mf.write_skeleton(ALL_CHIPS_3MF, P.ALL_CHIPS_PARTS, P.ALL_CHIPS_PLATES, ALL_CHIPS_TITLE)
    written.append(ALL_CHIPS_3MF)
    make_3mf.write_skeleton(DOCKS_SET_3MF, P.DOCKS_SET_PARTS, P.DOCKS_SET_PLATES, DOCKS_SET_TITLE)
    written.append(DOCKS_SET_3MF)
    return written


def remove_stale(keep: set[Path]) -> list[Path]:
    """Delete files under prints/ that this run did not write (the README is kept), then any empty folders; return what was deleted."""
    removed = []
    for path in sorted(PRINTS.rglob("*")):
        if path.is_file() and path not in keep and path != README:
            path.unlink()
            removed.append(path)
    for folder in sorted((p for p in PRINTS.rglob("*") if p.is_dir()), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
    return removed


def readme_text() -> str:
    """The generated prints/README.md: what each file is and how to print it."""
    rel = lambda p: p.relative_to(PRINTS).as_posix()  # noqa: E731
    rows = [f"| `{rel(CHIPS_DIR / (chip_clip.chip_file_stem(m) + '.3mf'))}` | Chip for {m} |" for m in chip_clip.FILAMENTS]
    rows.append(f"| `{rel(ALL_CHIPS_3MF)}` | All {len(chip_clip.FILAMENTS)} chips above on one plate |")
    rows.append(f"| `{rel(DOCKS_SET_3MF)}` | Snapmaker U1 docks with socket fingers, slots 1 to 4, on one plate |")
    return "\n".join([
        "# Prints",
        "",
        "This folder is generated by `tools/build_prints.py` and rebuilt by GitHub Actions: do not edit the files by hand, change the model and let the build replace them.",
        "",
        "Each file is a Snapmaker Orca / Bambu-format 3MF holding geometry, parts and which filament each part uses, but no printer, process or filament settings: pick your printer's presets after opening.",
        "",
        "| File | What it is |",
        "| --- | --- |",
        *rows,
        "",
        "## Printing notes",
        "",
        "- Chip: print with the back face down. The body is filament 1 and the name is filament 2. Press the NTAG215 sticker into the recess in the back afterwards.",
        "- Dock set: the docks stand on their bottom stop, and the supports under the fingers are already enabled in the file.",
        "",
    ])


def main() -> int:
    """Build, publish, prune and document; return a shell exit code."""
    level = os.environ.get(LOG_LEVEL_ENV, "INFO").upper()
    logging.basicConfig(level=level, format=LOG_FORMAT)
    if level != "DEBUG":
        logging.getLogger("build123d").setLevel(logging.WARNING)  # build123d logs every extrude at INFO
    build_outputs()
    written = write_prints()
    for path in written:
        log.debug("wrote %s (%d bytes)", path.relative_to(ROOT), path.stat().st_size)
    for path in remove_stale(set(written)):
        log.info("removed stale %s", path.relative_to(ROOT))
    README.write_text(readme_text())
    log.info("published %d 3MF files and %s", len(written), README.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
