"""Export the finger dock for the blueprint: build/dock.step, plus build/blueprint.yml with notes that quote the model's own constants.

The drawing itself is rendered by common-blueprint-generator (https://github.com/csmarshall/common-blueprint-generator), from the
.github/workflows/blueprint.yml workflow. The config is generated rather than committed so the clearances in the notes always match chip_clip.

Run: uv run python tools/export_step.py
Then, to preview locally: uvx --from "common-blueprint-generator[ocp] @ git+https://github.com/csmarshall/common-blueprint-generator" blueprint render build/blueprint.yml
"""

from __future__ import annotations

import logging
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "u1"))
sys.path.insert(0, str(REPO / "chip"))

from build123d import export_step  # noqa: E402
from chip_clip import DOCK_FRONT_CLEARANCE, DOCK_SIDE_CLEARANCE, FIT_CLEARANCE, STICKER_DIAMETER  # type: ignore[import-not-found]  # noqa: E402
from u1_parts import dock_fingers_parts  # type: ignore[import-not-found]  # noqa: E402

log = logging.getLogger("export_step")

BUILD = REPO / "build"
STEP_PATH = BUILD / "dock.step"
CONFIG_PATH = BUILD / "blueprint.yml"


def config() -> str:
    """The blueprint.yml for the dock. Paths are relative to build/, where it is written."""
    notes = [
        "Print standing on the bottom stop. Supports under the snap fingers only.",
        f"Sliding fits from FIT_CLEARANCE {FIT_CLEARANCE:g}. Channel {DOCK_SIDE_CLEARANCE:g} per side, {DOCK_FRONT_CLEARANCE:g} front to back.",
        f"{STICKER_DIAMETER:g} mm NTAG215 sticker rides in the chip, centred on the socket axis.",
        "Snap fingers after Remmuleggu (Printables 1625982).",
    ]
    lines = [
        "# Generated by tools/export_step.py: edit that script, not this file.",
        "model: dock.step",
        "output: ../docs/images/blueprint_dock",
        "readme: ../README.md",
        "title: U1 TAG CLIP · FINGER DOCK",
        "drawing_number: STC-001",
        "for: Snapmaker U1 toolhead, filament slot 1",
        "material: PETG",
        "source: u1/u1_parts.py (dock_fingers_parts)",
        "drawn_by: C. MARSHALL",
        "company: Shermer Works",
        'front: "+Z"',
        'up: "+Y"',
        "captions:",
        "  front: socket face",
        "  top: snap fingers up",
        "notes:",
        *[f'  - "{n}"' for n in notes],
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write build/dock.step and build/blueprint.yml."""
    logging.basicConfig(level=os.environ.get("TAG_CLIP_LOG_LEVEL", "INFO"), format="%(asctime)s %(levelname)s %(name)s %(message)s")
    BUILD.mkdir(exist_ok=True)
    log.info("building the finger dock")
    export_step(dock_fingers_parts(None)["dock"], str(STEP_PATH))
    CONFIG_PATH.write_text(config())
    log.info("wrote %s and %s", STEP_PATH.relative_to(REPO), CONFIG_PATH.relative_to(REPO))


if __name__ == "__main__":
    main()
